import 'package:dio/dio.dart';
import 'package:injectable/injectable.dart';
import 'package:youtube_explode_dart/youtube_explode_dart.dart' as yt_exp;
import '../../features/music_player/domain/models/lyric_line.dart';

@lazySingleton
class LyricsService {
  final Dio _dio;
  final yt_exp.YoutubeExplode _yt = yt_exp.YoutubeExplode();

  // Pre-compiled regular expressions for better performance
  static final _metadataCleanupRegex = RegExp(
    r'[(\[](Official|Lyric|Music|Video|Audio|Visualizer|Explicit).*?[)\]]',
    caseSensitive: false,
  );
  static final _featureCleanupRegex = RegExp(
    r'\(f(eat|t)\..*?\)',
    caseSensitive: false,
  );
  static final _featureEndRegex = RegExp(r'feat\..*$', caseSensitive: false);
  static final _bracketsRegex = RegExp(r'\[.*?\]');
  static final _whitespaceRegex = RegExp(r'\s+');
  static final _tagRegex = RegExp(r'\[(\d+):(\d+)\.(\d+)\]');

  LyricsService(this._dio);

  Future<Map<String, String?>> fetchLyrics(
    String artist,
    String title, {
    String? youtubeId,
  }) async {
    // 1. Clean metadata
    final cleanArtist = _cleanMetadata(artist);
    final cleanTitle = _cleanMetadata(title);

    // If artist is generic, try to extract it from title
    String effectiveArtist = cleanArtist;
    String effectiveTitle = cleanTitle;

    if ((cleanArtist.toLowerCase() == 'web download' ||
            cleanArtist.toLowerCase() == 'unknown artist') &&
        cleanTitle.contains(' - ')) {
      final parts = cleanTitle.split(' - ');
      effectiveArtist = parts[0].trim();
      effectiveTitle = parts[1].trim();
    }

    // LAYER 1: Try exact match first (LRCLIB)
    try {
      print(
        'LyricsService: Fetching exact match for: $effectiveArtist - $effectiveTitle',
      );
      final response = await _dio.get(
        'https://lrclib.net/api/get',
        queryParameters: {
          'artist_name': effectiveArtist,
          'track_name': effectiveTitle,
        },
      );

      if (response.statusCode == 200) {
        final data = response.data;
        print('LyricsService: Exact match found in LRCLIB!');
        return {
          'synced': data['syncedLyrics'] as String?,
          'plain': data['plainLyrics'] as String?,
        };
      }
    } catch (e) {
      print('LyricsService: LRCLIB exact match failed at $e');
    }

    // LAYER 2: Try YouTube Captions if ID is available
    if (youtubeId != null) {
      final ytLyrics = await fetchFromYoutubeCaptions(youtubeId);
      if (ytLyrics['synced'] != null || ytLyrics['plain'] != null) {
        return ytLyrics;
      }
    }

    // LAYER 3: Fallback to LRCLIB search if exact/YT fails
    return _searchLyricsFallback(effectiveArtist, effectiveTitle);
  }

  Future<Map<String, String?>> fetchFromYoutubeCaptions(String videoId) async {
    try {
      print('LyricsService: Fetching YouTube captions for: $videoId');
      final manifest = await _yt.videos.closedCaptions.getManifest(videoId);

      if (manifest.tracks.isEmpty) {
        print('LyricsService: No captions found for this video.');
        return {'synced': null, 'plain': null};
      }

      // Priority:
      // 1. Manual English
      // 2. Auto-generated English
      // 3. Manual Indonesian
      // 4. Any English
      // 5. Any Track

      yt_exp.ClosedCaptionTrackInfo? selectedTrack;

      final tracks = manifest.tracks;

      // Look for manual English
      selectedTrack =
          tracks
              .where((t) => t.language.code == 'en' && !t.isAutoGenerated)
              .firstOrNull ??
          // Look for auto English
          tracks
              .where((t) => t.language.code == 'en' && t.isAutoGenerated)
              .firstOrNull ??
          // Look for manual Indonesian
          tracks
              .where((t) => t.language.code == 'id' && !t.isAutoGenerated)
              .firstOrNull ??
          // Look for any English
          tracks.where((t) => t.language.code.startsWith('en')).firstOrNull ??
          // Take the first available
          tracks.first;

      print(
        'LyricsService: Selected caption track: ${selectedTrack.language.name} (${selectedTrack.language.code}) - Auto: ${selectedTrack.isAutoGenerated}',
      );

      final track = await _yt.videos.closedCaptions.get(selectedTrack);

      if (track.captions.isEmpty) {
        return {'synced': null, 'plain': null};
      }

      final synced = _convertToLrc(track);
      final plain = track.captions.map((c) => c.text).join('\n');

      return {'synced': synced, 'plain': plain};
    } catch (e) {
      print('LyricsService: YouTube caption fetch failed: $e');
      return {'synced': null, 'plain': null};
    }
  }

  String _convertToLrc(yt_exp.ClosedCaptionTrack track) {
    final buffer = StringBuffer();
    for (var caption in track.captions) {
      final start = caption.offset;
      final min = start.inMinutes.toString().padLeft(2, '0');
      final sec = (start.inSeconds % 60).toString().padLeft(2, '0');
      // LRC ms is 2 digits
      final ms = (start.inMilliseconds % 1000 ~/ 10).toString().padLeft(2, '0');

      buffer.writeln('[$min:$sec.$ms] ${caption.text.replaceAll('\n', ' ')}');
    }
    return buffer.toString();
  }

  Future<Map<String, String?>> _searchLyricsFallback(
    String artist,
    String title,
  ) async {
    try {
      final query =
          artist.toLowerCase() == 'web download' ||
              artist.toLowerCase() == 'unknown artist'
          ? title
          : '$artist $title';

      print('LyricsService: Searching fallback for: $query');
      final response = await _dio.get(
        'https://lrclib.net/api/search',
        queryParameters: {'q': query},
      );

      if (response.statusCode == 200 &&
          response.data is List &&
          (response.data as List).isNotEmpty) {
        final tracks = response.data as List;
        print('LyricsService: Found ${tracks.length} results in search.');

        // Find first with synced lyrics, otherwise use first result
        final bestMatch = tracks.firstWhere(
          (t) => t['syncedLyrics'] != null,
          orElse: () => tracks.first,
        );

        print(
          'LyricsService: Selected best match: ${bestMatch['artistName']} - ${bestMatch['trackName']}',
        );
        return {
          'synced': bestMatch['syncedLyrics'] as String?,
          'plain': bestMatch['plainLyrics'] as String?,
        };
      } else {
        print('LyricsService: No results found in fallback search.');
      }
    } catch (e) {
      print('LyricsService: Fallback search failed completely: $e');
    }
    return {'synced': null, 'plain': null};
  }

  String _cleanMetadata(String text) {
    if (text.isEmpty) return text;

    return text
        // Remove common YouTube tags in brackets/parentheses
        .replaceAll(_metadataCleanupRegex, '')
        // Remove features
        .replaceAll(_featureCleanupRegex, '')
        .replaceAll(_featureEndRegex, '')
        // Remove anything else in brackets (often junk)
        .replaceAll(_bracketsRegex, '')
        // Clean up whitespace
        .replaceAll(_whitespaceRegex, ' ')
        .trim();
  }

  List<LyricLine> parseLrc(String lrc) {
    if (lrc.isEmpty) return [];

    final lines = lrc.split('\n');
    final lyricLines = <LyricLine>[];

    for (var line in lines) {
      // Find all timestamp matches in the line
      final matches = _tagRegex.allMatches(line);
      if (matches.isEmpty) continue;

      // Extract text: everything that is not a tag
      final text = line.replaceAll(_bracketsRegex, '').trim();
      if (text.isEmpty) continue;

      for (var match in matches) {
        final minutes = int.parse(match.group(1)!);
        final seconds = int.parse(match.group(2)!);
        final fractionStr = match.group(3)!;

        // Accurate millisecond calculation:
        // .x   -> x * 100
        // .xx  -> x * 10
        // .xxx -> x
        int milliseconds = int.parse(fractionStr);
        if (fractionStr.length == 1) {
          milliseconds *= 100;
        } else if (fractionStr.length == 2) {
          milliseconds *= 10;
        }

        final startTime = Duration(
          minutes: minutes,
          seconds: seconds,
          milliseconds: milliseconds,
        );

        lyricLines.add(LyricLine(startTime: startTime, text: text));
      }
    }

    // Sort by start time (important for correct index tracking)
    lyricLines.sort((a, b) => a.startTime.compareTo(b.startTime));

    return lyricLines;
  }
}
